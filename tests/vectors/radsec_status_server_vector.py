#!/usr/bin/env python3
"""Known-answer vector for the RFC 5997 Status-Server probe the proxy sends to
a RadSec home server, written from the RFC text with only the Python standard
library. It shares no code with the Rust implementation; the Rust test
`status_server_probe_matches_the_radsec_known_answer_vector` in
crates/radius-server/src/proxy/health.rs pins its output.

    python3 -I tests/vectors/radsec_status_server_vector.py          # print vector
    python3 -I tests/vectors/radsec_status_server_vector.py --rust   # as Rust consts

References:
  RFC 6614 §2.3  RadSec uses the fixed shared secret "radsec" for the RADIUS
                 Authenticator / Message-Authenticator computations.
  RFC 5997 §3    Status-Server (Code 12) carries a random 16-octet Request
                 Authenticator; §4.1: the request MUST contain a
                 Message-Authenticator.
  RFC 2869 §5.14 Message-Authenticator (Type 80, Length 18) = HMAC-MD5 keyed
                 with the shared secret over the whole packet (Code, Identifier,
                 Length, Request Authenticator, attributes) with the
                 Message-Authenticator value set to 16 zero octets.
  RFC 2865 §3    Packet header layout: Code (1), Identifier (1), Length (2,
                 big-endian), Authenticator (16).
"""
import hashlib
import hmac
import sys

RADSEC_SECRET = b"radsec"  # RFC 6614 §2.3, a public constant
CODE_STATUS_SERVER = 12
ATTR_MESSAGE_AUTHENTICATOR = 80

# Fixed probe inputs (the implementation draws both at random per probe).
IDENTIFIER = 0x5A
REQUEST_AUTHENTICATOR = bytes(range(0xA0, 0xB0))


def status_server(identifier, request_authenticator, secret):
    """Encode the probe: header + Message-Authenticator (zeroed), then fill
    the HMAC-MD5 in. Returns (packet, message_authenticator)."""
    attrs_len = 2 + 16
    length = 20 + attrs_len
    header = bytes([CODE_STATUS_SERVER, identifier]) + length.to_bytes(2, "big")
    zeroed = header + request_authenticator + bytes([ATTR_MESSAGE_AUTHENTICATOR, attrs_len]) + bytes(16)
    assert len(zeroed) == length
    mac = hmac.new(secret, zeroed, hashlib.md5).digest()
    return zeroed[:-16] + mac, mac


def self_check():
    """RFC 2202 HMAC-MD5 test case 2 proves the HMAC before it is trusted."""
    digest = hmac.new(b"Jefe", b"what do ya want for nothing?", hashlib.md5).hexdigest()
    assert digest == "750c783e6ab0b503eaa86e310a5db738", digest


def main(argv):
    self_check()
    packet, mac = status_server(IDENTIFIER, REQUEST_AUTHENTICATOR, RADSEC_SECRET)
    if "--rust" in argv:
        print("    // Generated by tests/vectors/radsec_status_server_vector.py")
        print(f"    const KAT_IDENTIFIER: u8 = 0x{IDENTIFIER:02x};")
        print(f'    const KAT_REQUEST_AUTHENTICATOR: &str = "{REQUEST_AUTHENTICATOR.hex()}";')
        print(f'    const KAT_MESSAGE_AUTHENTICATOR: &str = "{mac.hex()}";')
        print(f'    const KAT_PACKET: &str = "{packet.hex()}";')
    else:
        print(f"secret                = {RADSEC_SECRET!r}")
        print(f"identifier            = 0x{IDENTIFIER:02x}")
        print(f"request authenticator = {REQUEST_AUTHENTICATOR.hex()}")
        print(f"message authenticator = {mac.hex()}")
        print(f"packet ({len(packet)} octets)   = {packet.hex()}")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
