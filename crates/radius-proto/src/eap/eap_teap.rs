    fn teap_packet_parses_outer_tlvs_after_tls_data() {
        // O bit: Outer TLV Length field, then TLS Data, then the Outer TLVs.
        let outer = TeapTlv::new(TlvType::AuthorityId, false, b"srv".to_vec()).to_bytes();
        let tls_data = vec![0x16, 0x03, 0x03];
        let mut data = vec![TeapPacket::FLAG_OUTER_TLV_LENGTH | TEAP_VERSION];
        data.extend_from_slice(&(outer.len() as u32).to_be_bytes());
        data.extend_from_slice(&tls_data);
        data.extend_from_slice(&outer);
        let parsed = TeapPacket::from_eap_data(&data).unwrap();
        assert_eq!(parsed.outer_tlvs, outer);
        assert_eq!(parsed.tls.tls_data, tls_data);
        assert_eq!(parsed.to_eap_data(), data);

        // With L, the Message Length covers the Outer TLV Length field and the
        // Outer TLVs; the TLS Message Length handed to the reassembler does not.
        let mut with_len =
            vec![TlsFlags::LENGTH_INCLUDED | TeapPacket::FLAG_OUTER_TLV_LENGTH | TEAP_VERSION];
        with_len.extend_from_slice(&((4 + tls_data.len() + outer.len()) as u32).to_be_bytes());
        with_len.extend_from_slice(&data[1..]);
        let parsed = TeapPacket::from_eap_data(&with_len).unwrap();
        assert_eq!(parsed.tls.tls_message_length, Some(tls_data.len() as u32));
        assert_eq!(parsed.outer_tlvs, outer);
        assert_eq!(parsed.to_eap_data(), with_len);

        // Outer TLV Length larger than the payload, or malformed Outer TLVs.
        let mut too_long = data.clone();
        too_long[4] = 0xFF;
        assert!(TeapPacket::from_eap_data(&too_long).is_err());
        let mut junk = data.clone();
        let n = junk.len();
        junk[n - outer.len()] = 0xC0; // sets the reserved R bit of the TLV
        assert!(TeapPacket::from_eap_data(&junk).is_err());

        // Outer TLVs on a fragmented message are not supported: fail closed.
        let mut fragmented = data;
        fragmented[0] |= TlsFlags::MORE_FRAGMENTS;
        assert!(matches!(
            TeapPacket::from_eap_data(&fragmented),
            Err(EapError::FragmentationNotSupported)
        ));
    }

