    /// RFC 9930 §4.2.13 / §6.3: the Binding Request TLV and its BUFFER, and
    /// the Binding Response the peer must answer with.
    #[test]
    fn crypto_binding_tlvs_match_independent_vectors() {
        for kat in &KATS {
            let cb = CryptoBinding::with_nonce(
                kat.hash,
                &unhex(kat.session_key_seed),
                &zero_imsk(),
                kat_nonce(),
            );
            let mut request = CryptoBindingTlv::new(
                CryptoBindingTlv::SUBTYPE_REQUEST,
                CryptoBindingTlv::FLAGS_MSK,
                1,
                cb.server_nonce,
            );
            let buffer = request.mac_buffer(&[], &[]);
            assert_eq!(
                hex::encode(&buffer),
                kat.request_buffer,
                "{:?} BUFFER",
                kat.hash
            );
            assert_eq!(buffer.len(), 80 + 1);
            assert_eq!(buffer[80], TEAP_EAP_TYPE);
            request.msk_compound_mac = CryptoBinding::compound_mac(kat.hash, &cb.cmk, &buffer);
            assert_eq!(
                hex::encode(request.to_tlv().to_bytes()),
                kat.request_tlv,
                "{:?} Binding Request",
                kat.hash
            );

            let mut response = CryptoBindingTlv::new(
                CryptoBindingTlv::SUBTYPE_RESPONSE,
                CryptoBindingTlv::FLAGS_MSK,
                1,
                CryptoBinding::response_nonce(&cb.server_nonce),
            );
            let buffer = response.mac_buffer(&[], &[]);
            response.msk_compound_mac = CryptoBinding::compound_mac(kat.hash, &cb.cmk, &buffer);
            assert_eq!(
                hex::encode(response.to_tlv().to_bytes()),
                kat.response_tlv,
                "{:?} Binding Response",
                kat.hash
            );

            // And the same vector verifies.
            let parsed = CryptoBindingTlv::from_tlv(
                &TeapTlv::parse_tlvs(&unhex(kat.response_tlv)).unwrap()[0],
            )
            .unwrap();
            assert!(CryptoBinding::verify_compound_mac(
                kat.hash,
                &cb.cmk,
                &parsed.mac_buffer(&[], &[]),
                &parsed.msk_compound_mac
            ));
            let mut bad = parsed.msk_compound_mac;
            bad[0] ^= 1;
            assert!(!CryptoBinding::verify_compound_mac(
                kat.hash,
                &cb.cmk,
                &parsed.mac_buffer(&[], &[]),
                &bad
            ));
        }
    }

    /// Outer TLVs of the first messages enter the BUFFER (§6.3 items 3 and 4)
    /// and therefore change the Compound-MAC.
    #[test]
    fn compound_mac_covers_outer_tlvs() {
        let cb = CryptoBinding::with_nonce(
            TeapHash::Sha256,
            &unhex(SHA256_SESSION_KEY_SEED),
            &zero_imsk(),
            kat_nonce(),
        );
        let request = CryptoBindingTlv::new(
            CryptoBindingTlv::SUBTYPE_REQUEST,
            CryptoBindingTlv::FLAGS_MSK,
            1,
            cb.server_nonce,
        );
        let outer = TeapTlv::new(TlvType::AuthorityId, false, b"id".to_vec()).to_bytes();
        let plain =
            CryptoBinding::compound_mac(TeapHash::Sha256, &cb.cmk, &request.mac_buffer(&[], &[]));
        let with_server = CryptoBinding::compound_mac(
            TeapHash::Sha256,
            &cb.cmk,
            &request.mac_buffer(&outer, &[]),
        );
        let with_peer = CryptoBinding::compound_mac(
            TeapHash::Sha256,
            &cb.cmk,
            &request.mac_buffer(&[], &outer),
        );
        assert_ne!(plain, with_server);
        assert_ne!(plain, with_peer);
        // No boundary marker between items 3 and 4: the RFC accepts this.
        assert_eq!(with_server, with_peer);
    }

