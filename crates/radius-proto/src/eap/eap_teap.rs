    #[test]
    fn invalid_crypto_binding_response_fails_closed() {
        // Wrong MAC.
        let (mut server, request) = server_awaiting_binding();
        let answer = peer_binding_answer(&server, &request, false);
        assert!(matches!(
            server.process_result_ack(&answer),
            Err(EapError::AuthenticationFailed)
        ));
        assert!(!server.crypto_binding_verified);
        assert!(server.get_msk().is_none());

        // Field-level checks (§4.2.13), each on a fresh server.
        type Mutator = Box<dyn Fn(&mut CryptoBindingTlv)>;
        let variants: Vec<(&str, Mutator)> = vec![
            ("version 2", Box::new(|cb| cb.version = 2)),
            ("received version 2", Box::new(|cb| cb.received_version = 2)),
            (
                "sub-type request",
                Box::new(|cb| cb.sub_type = CryptoBindingTlv::SUBTYPE_REQUEST),
            ),
            ("flags 0", Box::new(|cb| cb.flags = 0)),
            (
                "flags EMSK only",
                Box::new(|cb| cb.flags = CryptoBindingTlv::FLAGS_EMSK),
            ),
            (
                "flags EMSK and MSK",
                Box::new(|cb| cb.flags = CryptoBindingTlv::FLAGS_EMSK_AND_MSK),
            ),
            (
                "request nonce echoed unchanged",
                Box::new(|cb| cb.nonce[31] &= !1),
            ),
            ("other nonce", Box::new(|cb| cb.nonce[0] ^= 0xFF)),
        ];
        for (name, mutate) in variants {
            let (mut server, request) = server_awaiting_binding();
            let mut answer = peer_binding_answer(&server, &request, true);
            let mut cb = CryptoBindingTlv::from_tlv(&answer[1]).unwrap();
            mutate(&mut cb);
            // Re-MAC so only the field under test is wrong.
            let keys = server.crypto_binding.as_ref().unwrap();
            cb.msk_compound_mac =
                CryptoBinding::compound_mac(keys.hash, &keys.cmk, &cb.mac_buffer(&[], &[]));
            answer[1] = cb.to_tlv();
            assert!(
                server.process_result_ack(&answer).is_err(),
                "{name} must be rejected"
            );
            assert!(server.get_msk().is_none(), "{name}: no MSK");
        }
    }

