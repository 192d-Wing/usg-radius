//! EAP-TEAP (Tunnel Extensible Authentication Protocol)
//!
//! Implementation of RFC 9930 — Tunnel Extensible Authentication Protocol
//! (TEAP) Version 1, which obsoletes RFC 7170. Section numbers below refer to
//! RFC 9930 unless marked otherwise.
//!
//! TEAP is a two-phase authentication protocol:
//! - Phase 1: TLS tunnel establishment (reuses the EAP-TLS infrastructure)
//! - Phase 2: TLV-based inner authentication inside the encrypted tunnel
//!
//! # Architecture
//!
//! ```text
//! Phase 1: TLS Handshake (using EapTlsServer)
//!     ↓
//! Phase 2: TLV Protocol (Appendix C.1)
//!     <- Basic-Password-Auth-Req TLV (or EAP-Payload TLV), Identity-Type TLV
//!     Basic-Password-Auth-Resp TLV, Identity-Type TLV ->
//!     <- Intermediate-Result TLV (Success), Result TLV (Success),
//!        Crypto-Binding TLV (Request)
//!     Intermediate-Result TLV (Success), Crypto-Binding TLV (Response),
//!        Result TLV (Success) ->
//!     <- EAP-Success (MSK released to the Access-Accept builder)
//! ```
//!
//! The Crypto-Binding TLV (§4.2.13), its Compound MAC (§6.3) and the
//! IMCK/CMK/MSK key schedule (§6.2, §6.4) are pinned by known-answer vectors
//! generated by an independent implementation
//! (`tests/vectors/teap_rfc9930_vectors.py`) and exercised against
//! wpa_supplicant's `eapol_test` in `tests/interop/`.
//!
//! # Example
//!
//! ```no_run
//! # use radius_proto::eap::eap_teap::*;
//! # use radius_proto::eap::eap_tls::*;
//! # use std::sync::Arc;
//! # use rustls::ServerConfig;
//! # let config = Arc::new(ServerConfig::builder().with_no_client_auth().with_single_cert(vec![], rustls::pki_types::PrivateKeyDer::Pkcs8(vec![].into())).unwrap());
//! // Create TEAP server
//! let mut server = EapTeapServer::new(config);
//!
//! // Initialize connection (Phase 1)
//! server.initialize_connection().unwrap();
//!
//! // Process client messages...
//! ```

