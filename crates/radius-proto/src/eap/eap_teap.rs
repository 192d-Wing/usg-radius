    /// The peer's answer to the server's binding message: Intermediate-Result,
    /// Crypto-Binding Response (MAC over the §6.3 BUFFER with the server's
    /// CMK) and Result, as wpa_supplicant orders them.
    fn peer_binding_answer(
        server: &EapTeapServer,
        request: &TeapTlv,
        valid_mac: bool,
    ) -> Vec<TeapTlv> {
        let request = CryptoBindingTlv::from_tlv(request).unwrap();
        let cb = server.crypto_binding.as_ref().unwrap();
        let mut response = CryptoBindingTlv::new(
            CryptoBindingTlv::SUBTYPE_RESPONSE,
            CryptoBindingTlv::FLAGS_MSK,
            request.version,
            CryptoBinding::response_nonce(&request.nonce),
        );
        response.msk_compound_mac = if valid_mac {
            CryptoBinding::compound_mac(cb.hash, &cb.cmk, &response.mac_buffer(&[], &[]))
        } else {
            [0xEE; 20]
        };
        vec![
            TeapResult::Success.to_intermediate_result_tlv(),
            response.to_tlv(),
            TeapResult::Success.to_result_tlv(),
        ]
    }

